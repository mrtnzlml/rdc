    #[test]
    fn queues_group_under_workspace_with_engine_and_folded_counts() {
        let dir = tempfile::TempDir::new().unwrap();
        let paths = Paths::for_env(dir.path(), "dev");
        let q_dir = paths.queue_dir("main", "invoices");
        std::fs::create_dir_all(q_dir.join("formulas")).unwrap();
        std::fs::write(
            paths.workspace_dir("main").join("workspace.json"),
            r#"{"id":700,"name":"Main"}"#,
        )
        .unwrap();
        std::fs::write(
            q_dir.join("queue.json"),
            r#"{"id":100,"name":"Invoices","engine":"rdc://engines/inv",
               "schema":"rdc://schemas/invoices","inbox":"rdc://inboxes/invoices"}"#,
        )
        .unwrap();
        std::fs::write(q_dir.join("formulas/amount_total.py"), b"a+b").unwrap();
        std::fs::write(q_dir.join("formulas/invoice_id.py"), b"x").unwrap();
        // A hook naming the queue: listed on the hook's line, not the queue's.
        std::fs::create_dir_all(paths.hooks_dir()).unwrap();
        std::fs::write(
            paths.hooks_dir().join("validator.json"),
            r#"{"id":1,"name":"V","queues":["rdc://queues/invoices"]}"#,
        )
        .unwrap();

        let mut lf = Lockfile::default();
        lf.upsert("workspaces", "main", entry(700));
        lf.upsert("workspaces", "empty", entry(701));
        lf.upsert("queues", "invoices", entry(100));
        lf.upsert("queues", "orphan", entry(102));
        lf.upsert("schemas", "invoices", entry(200));
        lf.upsert("inboxes", "invoices", entry(300));
        lf.upsert("engines", "inv", entry(3));
        lf.upsert("hooks", "validator", entry(1));
        lf.upsert("email_templates", "main/invoices/rejection", entry(5));

        let body = index_of(&paths, &lf);
        assert!(
            body.contains(
                "### `main` (id 700) \"Main\"\n\n\
                 - `invoices` (id 100) \"Invoices\" · engine `inv`\n"
            ),
            "{body}"
        );
        assert!(body.contains("### `empty` (id 701)\n\n### "), "{body}");
        assert!(body.contains("### not on disk\n\n- `orphan` (id 102)\n"), "{body}");
        // Folded kinds get no section of their own.
        for gone in ["## workspaces", "## schemas", "## inboxes", "## email_templates"] {
            assert!(!body.contains(gone), "{gone}: {body}");
        }
        // The reverse link is gone; the hook carries the only one.
        assert_eq!(body.matches("`invoices`").count(), 2, "queue line + hook line: {body}");
    }

