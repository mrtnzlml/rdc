    #[test]
    fn output_is_deterministic_across_runs() {
        let dir = tempfile::TempDir::new().unwrap();
        let paths = Paths::for_env(dir.path(), "dev");
        std::fs::create_dir_all(paths.queue_dir("ws-b", "q1")).unwrap();
        std::fs::create_dir_all(paths.queue_dir("ws-a", "q2")).unwrap();
        std::fs::create_dir_all(paths.hooks_dir()).unwrap();
        std::fs::write(paths.hooks_dir().join("a.json"), r#"{"id":1,"name":"A"}"#).unwrap();
        std::fs::write(paths.hooks_dir().join("b.json"), r#"{"id":2,"name":"B"}"#).unwrap();

        let mut lf = Lockfile::default();
        lf.upsert("hooks", "a", entry(1));
        lf.upsert("hooks", "b", entry(2));
        lf.upsert("queues", "q1", entry(10));
        lf.upsert("queues", "q2", entry(11));

        let body1 = index_of(&paths, &lf);
        let body2 = index_of(&paths, &lf);
        assert_eq!(body1, body2);
        // Workspaces sort by slug even when not in the lockfile.
        assert!(body1.find("`ws-a`").unwrap() < body1.find("`ws-b`").unwrap(), "{body1}");
    }

    #[test]
    fn name_with_newlines_or_huge_size_is_quoted_safely() {
        assert_eq!(quote_for_md("simple"), "\"simple\"");
        assert_eq!(quote_for_md("two\nlines"), "\"two lines\"");
        let long = "x".repeat(200);
        let q = quote_for_md(&long);
        assert!(q.ends_with("…\""));
        assert!(q.chars().count() <= 123, "truncated form should be bounded");
    }

